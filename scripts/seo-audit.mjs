#!/usr/bin/env node

import { mkdir, readFile, readdir, stat, writeFile } from "node:fs/promises";
import { join, relative, resolve } from "node:path";

const root = resolve(new URL("..", import.meta.url).pathname);
const args = new Map();
for (let i = 2; i < process.argv.length; i += 1) {
  if (process.argv[i].startsWith("--")) {
    const [key, value] = process.argv[i].slice(2).split("=", 2);
    args.set(key, value ?? process.argv[i + 1] ?? true);
    if (value === undefined && process.argv[i + 1] && !process.argv[i + 1].startsWith("--")) i += 1;
  }
}

const publicDir = resolve(root, args.get("public-dir") || "public");
const reportDir = resolve(root, args.get("report-dir") || ".audit");
const baseUrl = new URL(args.get("base-url") || "https://www.properaccess.nl/");
const queryFile = resolve(root, args.get("queries") || "config/seo/ai-queries.json");

const checks = [];
const findings = [];
const addCheck = (id, status, message, details = {}) => checks.push({ id, status, message, ...details });
const addFinding = (severity, area, issue, evidence, recommendation) =>
  findings.push({ severity, area, issue, evidence, recommendation });

async function exists(path) {
  try {
    await stat(path);
    return true;
  } catch {
    return false;
  }
}

async function filesUnder(dir) {
  const result = [];
  async function visit(current) {
    for (const entry of await readdir(current, { withFileTypes: true })) {
      const path = join(current, entry.name);
      if (entry.isDirectory()) await visit(path);
      else result.push(path);
    }
  }
  await visit(dir);
  return result;
}

function clean(value) {
  return value.replace(/\s+/g, " ").trim();
}

function attr(tag, name) {
  const match = tag.match(new RegExp(`${name}\\s*=\\s*(?:(['"])([\\s\\S]*?)\\1|([^\\s>]+))`, "i"));
  return match?.[2] || match?.[3] || "";
}

function tags(html, name) {
  return [...html.matchAll(new RegExp(`<${name}\\b[^>]*>`, "gi"))].map((match) => match[0]);
}

function metaValue(html, name) {
  const tag = tags(html, "meta").find((candidate) => attr(candidate, "name").toLowerCase() === name.toLowerCase());
  return tag ? attr(tag, "content") : "";
}

function canonicalValue(html) {
  const tag = tags(html, "link").find((candidate) => attr(candidate, "rel").toLowerCase().split(/\\s+/).includes("canonical"));
  return tag ? attr(tag, "href") : "";
}

function urlForFile(file) {
  const rel = relative(publicDir, file).replaceAll("\\", "/");
  if (rel === "index.html") return "/";
  if (rel.endsWith("/index.html")) return `/${rel.slice(0, -"index.html".length)}`;
  return `/${rel}`;
}

function fileForUrl(pathname) {
  let path = decodeURIComponent(pathname).replace(/^\//, "");
  if (!path || path.endsWith("/")) path += "index.html";
  else if (!path.includes(".")) path += "/index.html";
  return join(publicDir, path);
}

function stripHtml(html) {
  return clean(
    html
      .replace(/<(script|style|noscript)[^>]*>[\s\S]*?<\/\1>/gi, " ")
      .replace(/<[^>]+>/g, " ")
      .replace(/&nbsp;/gi, " ")
      .replace(/&amp;/gi, "&")
      .replace(/&quot;/gi, '"')
      .replace(/&#39;/gi, "'")
  );
}

async function readJson(path, fallback) {
  try {
    return JSON.parse(await readFile(path, "utf8"));
  } catch {
    return fallback;
  }
}

if (!(await exists(publicDir))) {
  addCheck("build-output", "fail", `Buildmap ontbreekt: ${relative(root, publicDir)}`);
  await mkdir(reportDir, { recursive: true });
  await writeReports();
  process.exitCode = 1;
} else {
  const allFiles = await filesUnder(publicDir);
  const htmlFiles = allFiles.filter((file) => file.endsWith(".html"));
  const sitemapFiles = allFiles.filter((file) => /(^|\/)sitemap[^/]*\.xml$/i.test(relative(publicDir, file)));
  const sitemapUrls = new Set();
  for (const sitemapFile of sitemapFiles) {
    const sitemap = await readFile(sitemapFile, "utf8");
    for (const match of sitemap.matchAll(/<loc>([^<]+)<\/loc>/g)) {
      try {
        const target = new URL(match[1]);
        if (target.origin === baseUrl.origin) sitemapUrls.add(target.pathname);
      } catch {
        // The sitemap validation below reports malformed URLs.
      }
    }
  }
  const htmlByUrl = new Map();
  const pages = [];

  for (const file of htmlFiles) {
    const html = await readFile(file, "utf8");
    const url = urlForFile(file);
    // Report artifacts are deliberately excluded from the public SEO surface. Their
    // HTML is generated by a separate audit pipeline and is checked by its own
    // noindex guard in the deployment workflow.
    if (url === "/404.html" || url.startsWith("/rapporten/")) continue;
    if (sitemapUrls.size && !sitemapUrls.has(url)) continue;
    htmlByUrl.set(url, file);
    const title = clean(html.match(/<title[^>]*>([\s\S]*?)<\/title>/i)?.[1] || "");
    const description = clean(metaValue(html, "description"));
    const canonical = canonicalValue(html);
    const h1Count = (html.match(/<h1\b/gi) || []).length;
    const bodyText = stripHtml(html);
    const noindex = /noindex/i.test(metaValue(html, "robots"));
    const jsonLd = (html.match(/application\/ld\+json/gi) || []).length;
    const hasFaq = /faq|veelgestelde vragen|frequently asked/i.test(bodyText);
    const hasList = /<(ol|ul)\b/i.test(html);
    const hasSources = /\b(bron|volgens|source|according to|reference|verwijst naar)\b/i.test(bodyText) || /<(a|cite)\b[^>]*href=["']https?:\/\//i.test(html);
    const hreflangCount = (html.match(/hreflang=/gi) || []).length;
    pages.push({ url, file: relative(root, file), title, description, canonical, h1Count, noindex, jsonLd, hasFaq, hasList, hasSources, hreflangCount, wordCount: bodyText.split(/\s+/).filter(Boolean).length });
    if (!noindex) {
      if (!title) addFinding("high", "SEO", "Pagina heeft geen title", url, "Voeg een unieke en beschrijvende paginatitel toe.");
      if (!description) addFinding("medium", "SEO", "Pagina heeft geen meta description", url, "Voeg een unieke samenvatting toe die de zoekintentie beantwoordt.");
      if (h1Count !== 1) addFinding("medium", "SEO", `Pagina heeft ${h1Count} H1-koppen`, url, "Gebruik precies één duidelijke H1 per indexeerbare pagina.");
      if (!canonical) addFinding("high", "SEO", "Pagina heeft geen canonical", url, "Voeg een canonical URL toe.");
      if (!jsonLd) addFinding("medium", "AEO", "Pagina heeft geen JSON-LD", url, "Voeg alleen passende schema.org-gegevens toe; schema is ondersteunend, geen garantie op AI-citatie.");
      if (bodyText.length > 400 && !hasList && !hasFaq) addFinding("low", "AEO", "Pagina heeft geen herkenbare lijst of FAQ-structuur", url, "Overweeg een antwoordblok, stappenlijst of FAQ als dat bij de zoekvraag past.");
      const factHeavy = bodyText.length > 1000 && !url.startsWith("/academy/") && /(%|\\b20\\d{2}\\b|\\bvolgens\\b|\\baccording to\\b|\\bonderzoek\\b|\\bresearch\\b|\\bwetgeving\\b|\\blegislation\\b)/i.test(bodyText);
      if (factHeavy && !hasSources) addFinding("low", "AI", "Pagina bevat geen herkenbare bronverwijzing", url, "Noem bronnen, datum en deskundige context bij feitelijke claims.");
    }
  }

  addCheck("html-pages", "pass", `${pages.length} HTML-pagina's gevonden`, { count: pages.length });
  addCheck("indexable-pages", "pass", `${pages.filter((page) => !page.noindex).length} indexeerbare pagina's gecontroleerd`);

  for (const field of ["title", "description"]) {
    const byValue = new Map();
    for (const page of pages) {
      const value = page[field];
      if (!value || page.noindex) continue;
      // Een Nederlandse en Engelse pagina mogen dezelfde fallbacktitel hebben.
      // Zoek alleen dubbelen binnen dezelfde taalvariant.
      const language = page.url.startsWith("/en/") ? "en" : "nl";
      const key = `${language}\u0000${value}`;
      const urls = byValue.get(key) || [];
      urls.push(page.url);
      byValue.set(key, urls);
    }
    for (const [key, urls] of byValue) {
      if (urls.length < 2) continue;
      addFinding(
        field === "title" ? "medium" : "low",
        "SEO",
        `Indexeerbare pagina's delen dezelfde ${field}`,
        urls.join(" | "),
        `Maak de ${field} uniek per zoekintentie, of geef één pagina een passende canonical/noindex-instructie.`
      );
    }
  }

  const robotsPath = join(publicDir, "robots.txt");
  if (await exists(robotsPath)) {
    const robots = await readFile(robotsPath, "utf8");
    addCheck("robots", /Sitemap:\s*https?:\/\//i.test(robots) ? "pass" : "warn", "robots.txt gevonden", { sitemapDeclared: /Sitemap:\s*https?:\/\//i.test(robots) });
    if (/User-agent:\s*\*[^]*?Disallow:\s*\/\s*$/im.test(robots)) addFinding("high", "AI", "robots.txt blokkeert mogelijk de hele site", "User-agent * met Disallow: /", "Controleer botspecifieke regels en laat publieke content crawlbaar.");
    for (const bot of ["GPTBot", "PerplexityBot", "ClaudeBot", "Google-Extended"]) {
      if (new RegExp(`User-agent:\\s*${bot}[^]*?Disallow:\\s*\\/\\s*$`, "im").test(robots)) addFinding("high", "AI", `${bot} wordt geblokkeerd`, "robots.txt", "Verwijder de blokkade als citatie door dit platform gewenst is.");
    }
  } else addFinding("high", "SEO", "robots.txt ontbreekt", "/robots.txt", "Publiceer robots.txt met een geldige sitemapverwijzing.");

  if (sitemapFiles.length) {
    const locs = [];
    for (const sitemapFile of sitemapFiles) {
      const sitemap = await readFile(sitemapFile, "utf8");
      locs.push(...[...sitemap.matchAll(/<loc>([^<]+)<\/loc>/g)].map((match) => match[1]));
    }
    addCheck("sitemap", locs.length ? "pass" : "fail", `Sitemap bevat ${locs.length} URL's`, { count: locs.length });
    for (const loc of locs) {
      try {
        const target = new URL(loc);
        if (target.origin === baseUrl.origin && !(await exists(fileForUrl(target.pathname)))) addFinding("high", "SEO", "Sitemap verwijst naar een ontbrekende buildpagina", loc, "Verwijder de URL of herstel de pagina vóór publicatie.");
      } catch {
        addFinding("medium", "SEO", "Ongeldige URL in sitemap", loc, "Gebruik absolute, geldige URL's.");
      }
    }
  } else addFinding("high", "SEO", "sitemap.xml ontbreekt", "/sitemap.xml", "Laat Hugo de sitemap genereren en controleer die in de build.");

  for (const candidate of ["llms.txt", "llms-full.txt", "en/llms.txt", "en/llms-full.txt"]) {
    const found = await exists(join(publicDir, candidate));
    addCheck(`llms-${candidate.replaceAll("/", "-")}`, found ? "pass" : "warn", found ? `${candidate} gevonden` : `${candidate} ontbreekt`);
  }

  let brokenLinks = 0;
  for (const page of pages) {
    const html = await readFile(resolve(root, page.file), "utf8");
    const renderedHtml = html.replace(/<(pre|code)\b[^>]*>[\s\S]*?<\/\1>/gi, " ");
    for (const match of renderedHtml.matchAll(/\b(?:href|src)=["']([^"']+)["']/gi)) {
      const value = match[1];
      if (!value || value.startsWith("#") || /^(mailto:|tel:|javascript:|data:)/i.test(value)) continue;
      let target;
      try { target = new URL(value, new URL(page.url, baseUrl)); } catch { continue; }
      if (target.origin !== baseUrl.origin) continue;
      if (!(await exists(fileForUrl(target.pathname)))) {
        brokenLinks += 1;
        if (brokenLinks <= 25) addFinding("high", "SEO", "Interne link verwijst naar ontbrekende pagina", `${page.url} → ${target.pathname}`, "Herstel de link of maak de doelpagina aan.");
      }
    }
  }
  addCheck("internal-links", brokenLinks ? "fail" : "pass", brokenLinks ? `${brokenLinks} interne links lijken stuk` : "Geen ontbrekende interne doelen gevonden", { brokenLinks });

  const queries = await readJson(queryFile, []);
  addCheck("ai-query-set", queries.length ? "pass" : "warn", `${queries.length} vaste AI-zoekvragen klaar voor handmatige controle`, { queries });
  if (queries.length) addFinding("info", "AI", "Handmatige citatiecontrole nodig", queries.map((item) => item.query).join(" | "), "Test deze vragen wekelijks in ChatGPT, Perplexity en Google; noteer bronnen, concurrenten en gebruikte pagina's.");

  const result = { generatedAt: new Date().toISOString(), baseUrl: baseUrl.href, checks, findings, pages, manualAiQueries: queries };
  await mkdir(reportDir, { recursive: true });
  await writeFile(join(reportDir, "seo-aeo-ai-audit.json"), `${JSON.stringify(result, null, 2)}\n`);
  await writeReports(result);
  process.exitCode = checks.some((check) => check.status === "fail") || findings.some((finding) => finding.severity === "high" && finding.area === "SEO" && finding.issue.includes("ontbrekende")) ? 1 : 0;
}

async function writeReports(result = { generatedAt: new Date().toISOString(), baseUrl: baseUrl.href, checks, findings, pages: [], manualAiQueries: [] }) {
  const counts = result.findings.reduce((acc, finding) => { acc[finding.severity] = (acc[finding.severity] || 0) + 1; return acc; }, {});
  const lines = [
    "# SEO-, AEO- en AI-vindbaarheidsaudit",
    "",
    `Gegenereerd: ${result.generatedAt}`,
    `Basis-URL: ${result.baseUrl}`,
    "",
    `Samenvatting: ${counts.high || 0} hoog, ${counts.medium || 0} middel, ${counts.low || 0} laag, ${counts.info || 0} informatiepunt.`,
    "",
    "## Controles",
    "",
    "| Controle | Status | Resultaat |",
    "|---|---|---|",
    ...result.checks.map((check) => `| ${check.id} | ${check.status} | ${check.message.replaceAll("|", "\\|")} |`),
    "",
    "## Bevindingen",
    "",
    "| Ernst | Gebied | Probleem | Bewijs | Aanbeveling |",
    "|---|---|---|---|---|",
    ...result.findings.map((finding) => `| ${finding.severity} | ${finding.area} | ${finding.issue.replaceAll("|", "\\|")} | ${String(finding.evidence).replaceAll("|", "\\|")} | ${finding.recommendation.replaceAll("|", "\\|")} |`),
    "",
    "## Handmatige AI-controle",
    "",
    "Deze controle automatiseert geen logins of externe zoekopdrachten. Test de vragen in ChatGPT, Perplexity en Google en voeg de uitkomsten toe aan het wekelijkse logboek.",
    "",
    ...result.manualAiQueries.map((item, index) => `${index + 1}. **${item.language.toUpperCase()}** — ${item.query}`),
    "",
    "## Interpretatie",
    "",
    "Automatische checks signaleren technische en structurele risico's. Ze bewijzen niet dat een pagina wordt geciteerd door een AI-systeem. Citatiegedrag blijft platform-, vraag- en momentafhankelijk.",
    ""
  ];
  await mkdir(reportDir, { recursive: true });
  await writeFile(join(reportDir, "seo-aeo-ai-audit.md"), `${lines.join("\n")}\n`);
}
